package calc;

/**
 * ВІДПОВІДІ НА ТЕОРЕТИЧНІ ПИТАННЯ:
 *
 * 1. Поняття класу і об'єкту:
 *    - Клас (Class) — це шаблон, креслення або модель (тип даних), що описує стан (поля/атрибути) 
 *      та поведінку (методи), які будуть мати створені на його основі сутності.
 *    - Об'єкт (Object) — це конкретний екземпляр класу (інстанс), створений у пам'яті (за допомогою оператора new),
 *      який володіє власними конкретними значеннями атрибутів.
 *
 * 2. Атрибути і методи класу. Виклик методів:
 *    - Атрибути (поля/змінні екземпляра) — це змінні, оголошені всередині класу, які зберігають стан об'єкта.
 *    - Методи — це блоки коду (функції), що визначають поведінку об'єкта або класу та виконують певні дії над даними.
 *    - Виклик методів: для нестатичних методів здійснюється через екземпляр: об'єкт.метод(параметри);
 *      для статичних методів — через ім'я класу: Ім'яКласу.метод(параметри).
 *
 * 3. Методи get i set. Типізовані і безтипові (void) методи:
 *    - Методи get (геттери) — повертають значення закритого (private) поля (забезпечують інкапсуляцію).
 *    - Методи set (сеттери) — встановлюють або змінюють значення закритого поля, дозволяючи валідувати дані.
 *    - Типізовані методи — методи, які повертають значення певного типу (int, double, String тощо) за допомогою оператора return.
 *    - Безтипові (void) методи — методи, які виконують набір дій, але не повертають жодного значення (тип повернення void).
 *
 * 4. Конструктори класу:
 *    - Конструктор — спеціальний блок коду, який викликається автоматично при створенні об'єкта (new)
 *      та використовується для ініціалізації початкового стану (атрибутів) об'єкта.
 *    - Ім'я конструктора обов'язково збігається з іменем класу, і він не має типу повернення (навіть void).
 *    - Конструктор за замовчуванням — конструктор без параметрів, який ініціалізує поля базовими значеннями.
 *
 * 5. Перевантаження методів (Method Overloading):
 *    - Це можливість створення кількох методів або конструкторів з однаковим ім'ям у межах одного класу, 
 *      але з різним списком параметрів (кількістю, типами або порядком аргументів).
 *
 * 6. Поняття статичного атрибуту і методу класу:
 *    - Статичний атрибут (static field) — змінна, що належить усьому класу загалом, а не окремим об'єктам.
 *      Існує в єдиному екземплярі для всіх об'єктів цього класу.
 *    - Статичний метод (static method) — метод, який можна викликати без створення об'єкта класу (через Ім'яКласу.метод()).
 *      Статичні методи не мають доступу до нестатичних полів об'єкта через 'this'.
 *
 * 7. Поняття пакетів у Java:
 *    - Пакет (package) — це механізм групування пов'язаних класів, інтерфейсів і підпакетів у простори імен (фізично це папки).
 *    - Пакети запобігають конфліктам імен класів і регулюють рівні доступу (package-private).
 */
public class ExpressionCalculator {

    // Атрибути класу (параметри / аргументи виразу)
    // Варіант 14: R = (sin(x^2 + 4)^3 + 4.3) / sin^3(x^4)
    // Параметри виразу: x (аргумент), constant1 (4.0), constant2 (4.3), power (3)
    private double x;
    private double constant1;
    private double constant2;
    private int power;

    /**
     * Конструктор за замовчуванням.
     * Ініціалізує параметри конкретними значеннями за замовчуванням на розсуд студента.
     */
    public ExpressionCalculator() {
        this.x = 2.0;          // Конкретне початкове значення аргументу
        this.constant1 = 4.0;  // Константа під синусом: (x^2 + 4)
        this.constant2 = 4.3;  // Доданок у чисельнику: + 4.3
        this.power = 3;        // Степінь синуса
    }

    /**
     * Конструктор з параметрами (перевантажений конструктор).
     * Дозволяє ініціалізувати всі аргументи виразу заданими значеннями.
     */
    public ExpressionCalculator(double x, double constant1, double constant2, int power) {
        this.x = x;
        this.constant1 = constant1;
        this.constant2 = constant2;
        this.power = power;
    }

    // --- Методи get і set (Геттери та сеттери для кожного атрибута) ---

    public double getX() {
        return x;
    }

    public void setX(double x) {
        this.x = x;
    }

    public double getConstant1() {
        return constant1;
    }

    public void setConstant1(double constant1) {
        this.constant1 = constant1;
    }

    public double getConstant2() {
        return constant2;
    }

    public void setConstant2(double constant2) {
        this.constant2 = constant2;
    }

    public int getPower() {
        return power;
    }

    public void setPower(int power) {
        this.power = power;
    }

    /**
     * Нестатичний метод для обчислення значення виразу.
     * Використовує внутрішні атрибути поточного об'єкта (this).
     * 
     * @return значення виразу R, або Double.NaN якщо аргумент не входить в ОДЗ (знаменник = 0).
     */
    public double calculate() {
        double denominator = Math.pow(Math.sin(Math.pow(this.x, 4)), this.power);

        // Перевірка ОДЗ
        if (Math.abs(denominator) < 1e-10) {
            return Double.NaN;
        }

        double sinArg = this.x * this.x + this.constant1;
        double numerator = Math.pow(Math.sin(sinArg), this.power) + this.constant2;

        return numerator / denominator;
    }

    /**
     * Статичний метод для обчислення того самого виразу.
     * Не залежить від стану конкретного об'єкта і приймає всі аргументи як вхідні параметри.
     * 
     * @return значення виразу R, або Double.NaN якщо аргумент не входить в ОДЗ (знаменник = 0).
     */
    public static double calculateStatic(double x, double constant1, double constant2, int power) {
        double denominator = Math.pow(Math.sin(Math.pow(x, 4)), power);

        // Перевірка ОДЗ
        if (Math.abs(denominator) < 1e-10) {
            return Double.NaN;
        }

        double sinArg = x * x + constant1;
        double numerator = Math.pow(Math.sin(sinArg), power) + constant2;

        return numerator / denominator;
    }
}
